  /* ------------------------- pure helpers ------------------------- */

  function fmt(v, digits) {
    if (!isFinite(v)) return 'n/a';
    return Number(v).toFixed(digits === undefined ? 2 : digits);
  }

  function pct(v) { return (100 * v).toFixed(1) + '%'; }

  function safeNumber(value, fallback) {
    var n = Number(value);
    return isFinite(n) ? n : fallback;
  }

  /* Build the WFDB header text for the current record. The WFDB spec
     requires one signal-specification line per signal: file name, format
     with gain and units, then ADC resolution, ADC gain, baseline, zero,
     initial value and checksum, and finally the signal description. */
  function wfdbHeader(recordName, leadNames, nSamples, fs, gain) {
    var lines = [];
    lines.push(recordName + ' ' + leadNames.length + ' ' + fs + ' ' + nSamples);
    for (var L = 0; L < leadNames.length; L++) {
      lines.push(recordName + '.csv 16x' + gain + '(0)/mV 16 0 0 0 0 0 ' + leadNames[L]);
    }
    lines.push('# Synthetic 12-lead ECG generated by CardioWave DSP');
    lines.push('# Education and research only. Not a medical device. Not for diagnosis.');
    return lines.join('\n') + '\n';
  }

  /* Build the WFDB signal table as CSV. */
  function wfdbSignals(signals, leadNames, fs, gain) {
    var n = signals[0].length;
    var out = ['time_s,' + leadNames.join(',')];
    for (var i = 0; i < n; i++) {
      var row = [fmt(i / fs, 4)];
      for (var L = 0; L < signals.length; L++) row.push(Math.round(signals[L][i] * gain).toString());
      out.push(row.join(','));
    }
    return out.join('\n') + '\n';
  }

  /* Build a WFDB style annotation list. Type N marks a normal beat. */
  function wfdbAnnotations(peaks, fs) {
    var lines = ['# sample,time_s,type'];
    for (var i = 0; i < peaks.length; i++) {
      lines.push(peaks[i] + ',' + fmt(peaks[i] / fs, 4) + ',N');
    }
    return lines.join('\n') + '\n';
  }

  /*
   * Noisy detections can place two peaks on the same sample. A duplicated
   * timestamp makes the quadratic spline basis singular, so collapse the
   * beat list to strictly increasing samples before spectral analysis.
   * Detection scores always use the unmodified lists.
   */
  function dedupePeaks(peaks) {
    var out = [];
    for (var i = 0; i < peaks.length; i++) {
      if (i === 0 || peaks[i] > peaks[i - 1]) out.push(peaks[i]);
    }
    return out;
  }

  /* Run both detectors and score them against the generator ground truth. */
  function evaluateRecord(record, options) {
    var E = engines();
    var o = options || {};
    var votes = o.minVotes === undefined ? 4 : o.minVotes;
    var gate = o.gate === undefined ? 0.2 : o.gate;
    var tolerance = o.toleranceMs === undefined ? 50 : o.toleranceMs;
    var ensemble = E.Analysis.detectQRSEnsemble(record.signals, record.samplingRate, {
      minVotes: votes, gate: gate, toleranceMs: tolerance, refineMs: 60
    });
    var single = E.Analysis.detectQRS(record.signals[1], record.samplingRate);
    var hrvPeaks = dedupePeaks(ensemble.peaks);
    var hrv;
    try {
      hrv = E.Analysis.computeHRV(hrvPeaks, record.samplingRate);
    } catch (err) {
      /* Very short or degenerate beat lists still get a defined report. */
      hrv = E.Analysis.hrvTime(hrvPeaks, record.samplingRate);
      hrv.lf = 0; hrv.hf = 0; hrv.lfHf = 0; hrv.totalPower = 0;
      hrv.lfNormalized = 0; hrv.hfNormalized = 0;
      hrv.rrTimes = E.Analysis.rrTimes(hrvPeaks, record.samplingRate);
      hrv.degraded = true;
    }
    return {
      ensemble: ensemble,
      single: single,
      ensembleScore: E.Analysis.scoreDetection(ensemble.peaks, record.rPeaks, record.samplingRate, 150),
      singleScore: E.Analysis.scoreDetection(single.peaks, record.rPeaks, record.samplingRate, 150),
      hrvPeaks: hrvPeaks,
      hrv: hrv
    };
  }

