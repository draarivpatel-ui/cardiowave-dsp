  function runBenchmarkSuite(cases) {
    var E = engines();
    var list = cases || benchmarkCases();
    var rows = [];
    for (var i = 0; i < list.length; i++) {
      var c = list[i];
      var record = E.Cardio.generateECG({
        duration: c.duration, samplingRate: c.fs, heartRate: c.heartRate, seed: c.seed,
        humAmplitude: c.hum, wanderAmplitude: c.wander, emgAmplitude: c.emg
      });
      var ev = evaluateRecord(record, { minVotes: 4, gate: 0.2, toleranceMs: 50 });
      rows.push({
        label: c.label, heartRate: c.heartRate, fs: c.fs,
        noise: (c.hum + c.wander + c.emg).toFixed(2),
        reference: record.rPeaks.length,
        baseF1: ev.singleScore.f1, ensF1: ev.ensembleScore.f1,
        falsePositives: ev.ensembleScore.falsePositives,
        falseNegatives: ev.ensembleScore.falseNegatives,
        deltaF1: ev.ensembleScore.f1 - ev.singleScore.f1
      });
    }
    return rows;
  }

  /* Measured magnitude response of the three conditioning filters. */
  function filterVerification(fs) {
    var E = engines();
    var rate = fs || 250;
    var band = E.Filters.butter(1, [5, 15], 'bandpass', rate);
    var notch = E.Filters.butter(2, [59, 61], 'bandstop', rate);
    var hp = E.Filters.butter(2, [0.5], 'highpass', rate);
    return [
      { filter: 'QRS band-pass (order 1)', probe: 'gain at 10 Hz', measured: E.Filters.sosMagnitudeDb(band, 10, rate), expected: 'near 0 dB', pass: Math.abs(E.Filters.sosMagnitudeDb(band, 10, rate)) < 3 },
      { filter: 'QRS band-pass (order 1)', probe: 'gain at 0.5 Hz', measured: E.Filters.sosMagnitudeDb(band, 0.5, rate), expected: 'below -12 dB', pass: E.Filters.sosMagnitudeDb(band, 0.5, rate) < -12 },
      { filter: 'Mains notch (order 2)', probe: 'gain at 60 Hz', measured: E.Filters.sosMagnitudeDb(notch, 60, rate), expected: 'below -12 dB', pass: E.Filters.sosMagnitudeDb(notch, 60, rate) < -12 },
      { filter: 'Mains notch (order 2)', probe: 'gain at 30 Hz', measured: E.Filters.sosMagnitudeDb(notch, 30, rate), expected: 'above -3 dB', pass: E.Filters.sosMagnitudeDb(notch, 30, rate) > -3 },
      { filter: 'Wander high-pass (order 2)', probe: 'gain at 5 Hz', measured: E.Filters.sosMagnitudeDb(hp, 5, rate), expected: 'above -3 dB', pass: E.Filters.sosMagnitudeDb(hp, 5, rate) > -3 },
      { filter: 'Wander high-pass (order 2)', probe: 'gain at 0.05 Hz', measured: E.Filters.sosMagnitudeDb(hp, 0.05, rate), expected: 'below -20 dB', pass: E.Filters.sosMagnitudeDb(hp, 0.05, rate) < -20 }
    ];
  }

  /* Sweep the vote threshold on one record. */
  function voteSweep(record, gate, tolerance) {
    var E = engines();
    var out = [];
    for (var votes = 1; votes <= record.signals.length; votes++) {
      var e = E.Analysis.detectQRSEnsemble(record.signals, record.samplingRate, {
        minVotes: votes, gate: gate === undefined ? 0.2 : gate,
        toleranceMs: tolerance === undefined ? 50 : tolerance, refineMs: 60
      });
      var s = E.Analysis.scoreDetection(e.peaks, record.rPeaks, record.samplingRate, 150);
      out.push({ votes: votes, f1: s.f1, sensitivity: s.sensitivity, precision: s.positivePredictivity, detections: e.peaks.length });
    }
    return out;
  }

  /* ------------------------- canvas helpers ------------------------- */

  function setupCanvas(canvas, height) {
    if (!canvas) return null;
    var parent = canvas.parentNode;
    var available = (parent && parent.clientWidth) || canvas.clientWidth || 600;
    var w = Math.max(240, Math.min(1200, Math.floor(available)));
    var h = height || 220;
    var dpr = 1;
    if (typeof root !== 'undefined' && root.devicePixelRatio) dpr = Math.min(2, root.devicePixelRatio || 1);
    if (canvas.width !== undefined) {
      canvas.width = Math.floor(w * dpr);
      canvas.height = Math.floor(h * dpr);
    }
    if (canvas.style) {
      canvas.style.width = '100%';
      canvas.style.height = h + 'px';
    }
    var ctx = canvas.getContext ? canvas.getContext('2d') : null;
    if (!ctx) return null;
    if (ctx.setTransform) ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    if (ctx.clearRect) ctx.clearRect(0, 0, w, h);
    return { ctx: ctx, w: w, h: h };
  }

  function frame(ctx, w, h, pad) {
    var p = pad || { l: 44, r: 12, t: 14, b: 26 };
    ctx.fillStyle = '#0a1322';
    ctx.fillRect(0, 0, w, h);
    ctx.strokeStyle = PALETTE.grid;
    ctx.lineWidth = 1;
    for (var i = 0; i <= 4; i++) {
      var y = p.t + (h - p.t - p.b) * i / 4;
      ctx.beginPath(); ctx.moveTo(p.l, y); ctx.lineTo(w - p.r, y); ctx.stroke();
    }
    ctx.strokeStyle = PALETTE.axis;
    ctx.beginPath(); ctx.moveTo(p.l, p.t); ctx.lineTo(p.l, h - p.b); ctx.lineTo(w - p.r, h - p.b); ctx.stroke();
    return p;
  }

  function label(ctx, text, x, y, align) {
    ctx.fillStyle = PALETTE.text;
    ctx.font = '10px ui-monospace, monospace';
    ctx.textAlign = align || 'left';
    ctx.fillText(text, x, y);
    ctx.textAlign = 'left';
  }

  function polyline(ctx, getX, getY, count, color, width, dash) {
    if (count < 2) return;
    ctx.strokeStyle = color;
    ctx.lineWidth = width || 1.4;
    if (ctx.setLineDash) ctx.setLineDash(dash || []);
    ctx.beginPath();
    for (var i = 0; i < count; i++) {
      var x = getX(i), y = getY(i);
      if (i === 0) ctx.moveTo(x, y); else ctx.lineTo(x, y);
    }
    ctx.stroke();
    if (ctx.setLineDash) ctx.setLineDash([]);
  }

