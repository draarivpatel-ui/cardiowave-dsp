    function buildExport() {
      if (!state.record) { setStatus('Generate a record before exporting.', 'warn'); return; }
      /* Clamp the lead count into the exported 1..12 range: a raw '0'
         slices to an empty signal list and crashes on signals[0]. */
      var nLeads = Math.min(12, Math.max(1, Math.round(safeNumber(value('export-leads'), 12))));
      var names = state.record.leadNames.slice(0, nLeads === 1 ? 2 : nLeads);
      var signals;
      if (nLeads === 1) signals = [state.record.signals[1]];
      else signals = state.record.signals.slice(0, nLeads);
      if (nLeads === 1) names = ['II'];
      /* The ADC gain is written into the header verbatim and multiplies
         every exported sample, so it must be a finite positive value
         inside a range a 16-bit stream can express. */
      var gain = Math.min(10000, Math.max(1, Math.round(safeNumber(value('export-gain'), 200))));
      var recordName = (value('export-name') || 'cardiowave-synthetic').replace(/[^A-Za-z0-9_-]/g, '-');
      var annMode = value('export-ann') || 'detected';
      var ev = state.evaluation;
      var detected = ev ? ev.ensemble.peaks : [];
      var truth = state.record.rPeaks;
      var anns = annMode === 'truth' ? truth : annMode === 'both' ? detected.concat(truth.map(function (x) { return x; })) : detected;
      /* WFDB annotation streams must be non-decreasing in time. The
         'both' mode concatenates two independently sorted lists, which
         restarts the sample column mid-file; merge-sort and drop exact
         duplicates where detection and truth agree on a sample. */
      if (annMode === 'both') {
        anns = anns.slice().sort(function (a, b) { return a - b; }).filter(function (v, i, a) { return i === 0 || a[i - 1] !== v; });
      }
      state.exportFiles = {
        header: wfdbHeader(recordName, names, signals[0].length, state.record.samplingRate, gain),
        signals: wfdbSignals(signals, names, state.record.samplingRate, gain),
        annotations: wfdbAnnotations(anns, state.record.samplingRate),
        name: recordName
      };
      text(byId('export-preview'), state.exportFiles.header + '\n# signals CSV rows: ' + signals[0].length + '\n# annotations: ' + anns.length);
      text(byId('export-state'), names.length + ' leads | ' + signals[0].length + ' samples');
      ['download-header', 'download-signals', 'download-ann'].forEach(function (id) { var el = byId(id); if (el) el.disabled = false; });
      setStatus('WFDB text files built locally for ' + recordName + '. Use the download buttons to save them.', 'info');
    }

    function download(kind, ext) {
      if (!state.exportFiles) return;
      var content = state.exportFiles[kind];
      if (content === undefined) return;
      try {
        var blob = new w.Blob([content], { type: 'text/plain;charset=utf-8' });
        var url = w.URL.createObjectURL(blob);
        var a = d.createElement('a');
        a.href = url;
        a.download = state.exportFiles.name + '.' + ext;
        if (d.body && d.body.appendChild) d.body.appendChild(a);
        if (a.click) a.click();
        if (a.remove) a.remove();
        if (w.URL.revokeObjectURL) w.setTimeout(function () { w.URL.revokeObjectURL(url); }, 1000);
      } catch (e) {
        setStatus('Download unavailable in this environment. Copy the preview text instead.', 'warn');
      }
    }

